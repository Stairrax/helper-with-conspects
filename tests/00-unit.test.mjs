// Без браузера: чтение чисел и формул голосом Silero, сокращения.
import { createRequire } from 'node:module';
import { abbreviate } from '../js/abbr.js';

export default async ({ ok }) => {
  globalThis.self = globalThis;
  createRequire(import.meta.url)('../js/silero-core.js');
  const { normalize } = globalThis.SileroCore;
  const cases = [
    ['до 19 500 рублей', 'до девятнадцати тысяч пятисот рублей'],
    ['около 150 000 рублей', 'около ста пятидесяти тысяч рублей'],
    ['до 13 %', 'до тринадцати процентов'],
    ['до 21 рубля', 'до двадцати одного рубля'],
    ['более 2,5 %', 'более двух целых пяти десятых процента'],
    ['к 5 часам', 'к пяти часам'],
    ['к 300 рублям', 'к трёмстам рублям'],
    ['19 500 рублей', 'девятнадцать тысяч пятьсот рублей'],
    ['в 5 случаях', 'в пяти случаях'],
    ['в 5 раз больше', 'в пять раз больше'],
    ['на 2 страницах', 'на двух страницах'],
    ['на 5 частей', 'на пять частей'],
    ['о 3 законах', 'о трёх законах'],
    ['при 100 градусах', 'при ста градусах'],
    ['с 3 переменными', 'с тремя переменными'],
    ['между 2 точками', 'между двумя точками'],
    ['решается 3 способами', 'решается тремя способами'],
    ['с 200 рублями', 'с двумястами рублями'],
    ['с 1941 по 1945 год', 'с тысяча девятьсот сорок первого по тысяча девятьсот сорок пятый год'],
    ['21 задача', 'двадцать одна задача'],
    ['21 рубль', 'двадцать один рубль'],
    ['21 слово', 'двадцать одно слово'],
    ['2 формулы', 'две формулы'],
    ['2 рубля', 'два рубля'],
    ['задача 1 была решена', 'задача один была решена'],
    ['в 1 случае', 'в одном случае'],
    ['к 1 задаче', 'к одной задаче'],
    ['с 1 случаем', 'с одним случаем'],
    ['до 1 задачи', 'до одной задачи'],
    ['с 5 по 10 задачу', 'с пятой по десятую задачу'],
    ['с 2 по 4 пункт', 'со второго по четвёртый пункт'],
    ['150 000 рублей в год', 'сто пятьдесят тысяч рублей в год'],
    ['13 %', 'тринадцать процентов'],
    ['1 января 2026 года', 'первого января две тысячи двадцать шестого года'],
  ];
  for (const [src, want] of cases) ok(normalize(src) === want, `«${src}» → «${normalize(src)}»`);
  ok(/делить на/.test(normalize('a / b')), 'деление читается «делить на»');
  ok(/вэ/.test(normalize('w = 2')), 'латинская w — «вэ»');
  ok(abbreviate('налог на доходы физических лиц') === 'НДФЛ', 'сокращение НДФЛ');
  ok(abbreviate('Физических лиц много') === 'Физ. лиц много', 'сокращение с заглавной буквы');
};
