// Сокращения при диктовке: голос диктует, как преподаватель, — «физ. лиц», «НДФЛ», «РФ»,
// и на экране тот же сокращённый текст. Записывать быстрее, смысл тот же.

const B = '(?<![А-Яа-яЁё-])'; // граница слова (\b не работает с кириллицей)
const E = '(?![А-Яа-яЁё-])';
const S = '\\s+';
const A = '[а-яё]{1,3}'; // окончание прилагательного
const N = '[а-яё]{0,3}'; // окончание существительного

// [выражение, замена]; замена — строка ($1… — части слова) или функция
const RULES = [
  [`налог${N}${S}на${S}доходы${S}физических${S}лиц`, 'НДФЛ'],
  [`налог${N}${S}на${S}добавленную${S}стоимость`, 'НДС'],
  [`физическ${A}${S}(лиц${N})`, 'физ. $1'],
  [`юридическ${A}${S}(лиц${N})`, 'юр. $1'],
  [`российск${A}${S}федераци[а-яё]{1,2}`, 'РФ'],
  [`центральн${A}${S}банк${N}`, 'ЦБ'],
  [`индивидуальн${A}${S}предпринимател${N}`, 'ИП'],
  [`обществ${N}${S}с${S}ограниченной${S}ответственностью`, 'ООО'],
  [`валов${A}${S}внутренн${A}${S}продукт${N}`, 'ВВП'],
  [`коэффициент${N}${S}полезного${S}действия`, 'КПД'],
  [`минимальн${A}${S}размер${N}${S}оплаты${S}труда`, 'МРОТ'],
  [`федеральн${A}${S}налогов${A}${S}служб${N}`, 'ФНС'],
  [`министерств(${N})${S}финансов`, (m, end) => `Минфин${{ а: 'а', у: 'у', ом: 'ом', е: 'е' }[end] || ''}`],
  [`министерств${N}${S}внутренних${S}дел`, 'МВД'],
  [`министерств${N}${S}иностранных${S}дел`, 'МИД'],
  [`средств${N}${S}массовой${S}информации`, 'СМИ'],
  [`союз${N}${S}советских${S}социалистических${S}республик`, 'СССР'],
  [`соедин[её]нн${A}${S}штат${N}${S}америки`, 'США'],
  [`организаци[а-яё]{1,2}${S}объедин[её]нных${S}наций`, 'ООН'],
  [`европейск${A}${S}союз${N}`, 'ЕС'],
  [`дезоксирибонуклеинов${A}${S}кислот${N}`, 'ДНК'],
  [`рибонуклеинов${A}${S}кислот${N}`, 'РНК'],
  [`аденозинтрифосфорн${A}${S}кислот${N}`, 'АТФ'],
  [`аденозинтрифосфат${N}`, 'АТФ'],
  [`электродвижущ${A}${S}сил${N}`, 'ЭДС'],
  [`центральн${A}${S}нервн${A}${S}систем${N}`, 'ЦНС'],
  [`научно-техническ${A}${S}прогресс${N}`, 'НТП'],
  [`искусственн${A}${S}интеллект${N}`, 'ИИ'],
  [`персональн${A}${S}компьютер${N}`, 'ПК'],
  [`чрезвычайн${A}${S}ситуаци[а-яё]{1,2}`, 'ЧС'],
  [`жилищно-коммунальн${A}${S}хозяйств${N}`, 'ЖКХ'],
  [`дорожно-транспортн${A}${S}происшестви[а-яё]{1,2}`, 'ДТП'],
  [`един${A}${S}государственн${A}${S}экзамен${N}`, 'ЕГЭ'],
  [`гражданско-правов${A}${S}договор${N}`, 'ГПД'],
  [`(договор${N})${S}гражданско-правового${S}характера`, '$1 ГПХ'],
  // «госбюджет», «соцсети», «зарплата» — так и говорят
  [`государственн${A}${S}(бюджет|долг|пошлин|служащ|услуг|закуп|регистраци|сектор|орган|аппарат|облигаци)([а-яё]*)`, 'гос$1$2'],
  [`социальн${A}${S}(сет|защит|страховани|политик|выплат|сфер)([а-яё]*)`, 'соц$1$2'],
  [`заработн${A}${S}плат([а-яё]*)`, 'зарплат$1'],
  // на экране короче, голос всё равно читает полностью
  ['то есть', 'т. е.'],
  ['и так далее', 'и т. д.'],
  ['и тому подобное', 'и т. п.'],
  ['в том числе', 'в т. ч.'],
].map(([re, to]) => [new RegExp(B + re + E, 'gi'), to]);

/** Заменяет длинные термины сокращениями; заглавная буква в начале сохраняется. */
export function abbreviate(text) {
  let t = String(text || '');
  for (const [re, to] of RULES) {
    t = t.replace(re, (...args) => {
      const m = args[0];
      const end = args[args.length - 2] + m.length, str = args[args.length - 1];
      let out = typeof to === 'function' ? to(...args) : to.replace(/\$(\d)/g, (_, i) => args[+i] ?? '');
      // «Физических лиц…» в начале предложения -> «Физ. лиц…» (аббревиатуры и так заглавные)
      if (/^[А-ЯЁ]/.test(m) && /^[а-яё]/.test(out)) out = out[0].toUpperCase() + out.slice(1);
      if (out.endsWith('.') && str[end] === '.') out = out.slice(0, -1); // «в т. ч.» в конце предложения — одна точка
      return out;
    });
  }
  return t;
}
